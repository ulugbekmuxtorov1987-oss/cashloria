export const LEVELS: Level[] = levelMeta.map((meta, i) => ({
  ...meta,
  lessons: (grouped[i] ?? []).map((l) => ({ ...l, levelId: meta.id })),
}));

export const ALL_LESSONS: Lesson[] = LEVELS.flatMap((l) => l.lessons);

export function getLesson(id: string): Lesson | undefined {
  return ALL_LESSONS.find((l) => l.id === id);
}

/** Ordered lesson ids — the learning path unlock order. */
export const LESSON_ORDER: string[] = ALL_LESSONS.map((l) => l.id);

/** Lessons unlocked by default before any progress. */
export const FREE_LESSONS = 2;

export function nextLessonId(id: string): string | undefined {
  const i = LESSON_ORDER.indexOf(id);
  return i >= 0 ? LESSON_ORDER[i + 1] : undefined;
}
